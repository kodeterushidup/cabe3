import { Hono } from 'hono'
import { generateText, stepCountIs, tool } from 'ai'
import { describeRoute, resolver, validator } from 'hono-openapi'
import { z } from 'zod'
import type { AppEnv } from '../lib/env'
import { findInfluencerById, queryInfluencers } from '../lib/influencers'
import { provider } from '../lib/provider'
import { requireApiAuth } from '../middleware/auth'
import { requireQuota } from '../middleware/quota'

const MODEL_ID = 'liquid/lfm-3-1.7b:free'

const queryRequestSchema = z.object({
  prompt: z
    .string()
    .trim()
    .min(1)
    .max(2000)
    .describe(
      'Natural-language question about the influencers table, e.g. "Which Brazilian fitness creators have more than 100k followers?"',
    ),
})

const toolCallSchema = z.object({
  tool: z.string().describe('Name of the tool that was called'),
  input: z.record(z.string(), z.unknown()).describe('Arguments the model passed to the tool'),
  output: z.unknown().describe('JSON result returned by the tool'),
})

const queryResponseSchema = z.object({
  answer: z.string().describe('The text generated by the model after running the tools'),
  toolCalls: z
    .array(toolCallSchema)
    .describe('Every tool the model called, with its input and output, in order'),
})

const errorResponseSchema = z.object({
  error: z.string(),
  message: z.string(),
})

export const influencerQueryRoutes = new Hono<AppEnv>()

influencerQueryRoutes.post(
  '/influencers/query',
  requireApiAuth,
  requireQuota,
  describeRoute({
    tags: ['AI'],
    summary: 'Ask a natural-language question about the influencers table',
    description:
      'Requires a signed-in user and costs 1 request from their quota. Sends the prompt to `liquid/lfm-3-1.7b:free` on OpenRouter with two Vercel AI SDK tools: `searchInfluencers` runs a filtered, parameterised D1 query, and `getInfluencer` fetches one row by id. The endpoint returns the model answer plus every tool call and its result.',
    requestBody: {
      required: true,
      content: {
        'application/json': {
          schema: resolver(queryRequestSchema),
        },
      },
    },
    responses: {
      200: {
        description: 'The model answered after querying the influencers table',
        content: {
          'application/json': {
            schema: resolver(queryResponseSchema),
          },
        },
      },
      400: {
        description: 'Invalid request body',
        content: {
          'application/json': {
            schema: resolver(errorResponseSchema),
          },
        },
      },
      500: {
        description: 'The model call or the D1 query failed',
        content: {
          'application/json': {
            schema: resolver(errorResponseSchema),
          },
        },
      },
    },
  }),
  validator('json', queryRequestSchema, (result, c) => {
    if (!result.success) {
      return c.json(
        {
          error: 'Invalid request body',
          message: result.error.map((issue) => issue.message).join(', '),
        },
        400,
      )
    }
  }),
  async (c) => {
    const { prompt } = c.req.valid('json')

    try {
      const result = await generateText({
        model: provider(MODEL_ID),
        system: [
          'You answer questions about social-media influencers stored in a SQLite table.',
          'Use the provided tools to read the data before answering.',
          'Never invent influencers or numbers: when the tools return no rows, say so.',
          'Keep the answer short and mention the follower numbers you used.',
        ].join(' '),
        prompt,
        tools: {
          searchInfluencers: tool({
            description:
              'Search the influencers table with optional filters. Returns matching rows sorted by the given field (default: followers, highest first).',
            inputSchema: z.object({
              search: z
                .string()
                .optional()
                .describe('Free text matched against name, handle, bio, niche and niche description'),
              platform: z
                .enum([
                  'instagram',
                  'tiktok',
                  'youtube',
                  'x',
                  'facebook',
                  'linkedin',
                  'twitch',
                  'snapchat',
                  'pinterest',
                  'other',
                ])
                .optional()
                .describe('Only return influencers on this platform'),
              country: z
                .string()
                .length(2)
                .transform((value) => value.toUpperCase())
                .optional()
                .describe('ISO 3166-1 alpha-2 country code, e.g. "BR"'),
              region: z
                .string()
                .optional()
                .describe('Broad region stored on the row, e.g. "Europe" or "South America"'),
              niche: z.string().optional().describe('Exact niche label, e.g. "fitness"'),
              minFollowers: z
                .number()
                .int()
                .nonnegative()
                .optional()
                .describe('Minimum follower count (inclusive)'),
              maxFollowers: z
                .number()
                .int()
                .nonnegative()
                .optional()
                .describe('Maximum follower count (inclusive)'),
              verifiedOnly: z
                .boolean()
                .optional()
                .describe('When true, only return verified influencers'),
              sortBy: z
                .enum(['followers', 'totalPosts', 'engagementRate', 'name', 'updatedAt'])
                .optional()
                .describe('Field used to order the results (default: followers)'),
              sortDirection: z
                .enum(['asc', 'desc'])
                .optional()
                .describe('Sort direction (default: desc)'),
              limit: z
                .number()
                .int()
                .min(1)
                .max(50)
                .optional()
                .describe('How many rows to return (1-50, default 10)'),
              offset: z
                .number()
                .int()
                .nonnegative()
                .optional()
                .describe('Rows to skip, for pagination'),
            }),
            execute: async (input) => {
              const influencers = await queryInfluencers(c.env.DB, input)
              return { count: influencers.length, influencers }
            },
          }),
          getInfluencer: tool({
            description: 'Fetch a single influencer by its numeric database id.',
            inputSchema: z.object({
              id: z.number().int().positive().describe('The `id` column of the influencer row'),
            }),
            execute: async ({ id }) => {
              const influencer = await findInfluencerById(c.env.DB, id)
              return influencer
                ? { found: true, influencer }
                : { found: false, message: `No influencer with id ${id}` }
            },
          }),
        },
        stopWhen: stepCountIs(5),
      })

      const toolCalls = result.steps.flatMap((step) =>
        step.toolCalls.map((call) => {
          const toolResult = step.toolResults.find(
            (entry) => entry.toolCallId === call.toolCallId,
          )

          return {
            tool: call.toolName,
            input: call.input,
            output: toolResult?.output ?? null,
          }
        }),
      )

      return c.json({ answer: result.text, toolCalls })
    } catch (error) {
      console.error(error)

      return c.json(
        {
          error: 'Failed to query influencers',
          message: error instanceof Error ? error.message : String(error),
        },
        500,
      )
    }
  },
)
