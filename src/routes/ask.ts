import { Hono } from 'hono'
import { generateText } from 'ai'
import { describeRoute, resolver, validator } from 'hono-openapi'
import { z } from 'zod'
import { provider } from '../lib/provider'

const askRequestSchema = z.object({
  prompt: z.string().min(1).describe('The question to send to the AI'),
})

const askResponseSchema = z.object({
  answer: z.string().describe('The text generated by the AI'),
})

const errorResponseSchema = z.object({
  error: z.string(),
  message: z.string(),
})

export const askRoutes = new Hono()

askRoutes.post(
  '/ask',
  describeRoute({
    tags: ['AI'],
    summary: 'Ask the AI a question',
    description: 'Send a prompt to the AI model and get the generated answer.',
    requestBody: {
      required: true,
      content: {
        'application/json': {
          schema: resolver(askRequestSchema),
        },
      },
    },
    responses: {
      200: {
        description: 'The AI answer',
        content: {
          'application/json': {
            schema: resolver(askResponseSchema),
          },
        },
      },
      400: {
        description: 'Invalid request body',
        content: {
          'application/json': {
            schema: resolver(errorResponseSchema),
          },
        },
      },
      500: {
        description: 'Failed to generate a response',
        content: {
          'application/json': {
            schema: resolver(errorResponseSchema),
          },
        },
      },
    },
  }),
  validator('json', askRequestSchema, (result, c) => {
    if (!result.success) {
      return c.json(
        {
          error: 'Invalid request body',
          message: result.error.map((issue) => issue.message).join(', '),
        },
        400,
      )
    }
  }),
  async (c) => {
    const { prompt } = c.req.valid('json')

    try {
      const result = await generateText({
        model: provider('liquid/lfm-3-1.7b:free'),
        prompt,
      })

      return c.json({ answer: result.text })
    } catch (error) {
      console.error(error)
      return c.json(
        {
          error: 'Failed to generate a response',
          message: error instanceof Error ? error.message : String(error),
        },
        500,
      )
    }
  },
)
